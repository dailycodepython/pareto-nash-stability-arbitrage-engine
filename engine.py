import jax.numpy as jnp
from typing import Dict, Any

class StabilityArbitrageEngine:
    """
    Движок аналитической фильтрации сред на основе биматричных игр общего вида.

    Используется для выявления 'коридоров стабильности' (зон Рационального Альтруизма),
    где эгоистичные интересы децентрализованных агентов (Равновесие Нэша) совпали
    с глобальной эффективностью и общим благом всей системы (Оптимум Парето).
    """

    def __init__(self, threshold: float = 0.5):
        """
        Инициализация движка риск-фильтрации.

        Args:
            threshold (float): Порог дивергенции. Если расстояние между Нэшем
                               и Парето больше порога, система отклоняется.
        """
        self.threshold = threshold

    def _kl_divergence(self, p: jnp.ndarray, q: jnp.ndarray) -> float:
        """Расчет расстояния Кульбака-Лейблера (относительной энтропии) с клиппингом."""
        p_clipped = jnp.clip(p, 1e-7, 1.0)
        q_clipped = jnp.clip(q, 1e-7, 1.0)
        return float(jnp.sum(p_clipped * jnp.log(p_clipped / q_clipped)))

    def analyze_system(self, matrix_A: jnp.ndarray, matrix_B: jnp.ndarray) -> Dict[str, Any]:
        """
        Проводит полный биматричный аудит устойчивости среды.

        Args:
            matrix_A (jnp.ndarray): Платежная matrix Игрока 1 (Строки)
            matrix_B (jnp.ndarray): Платежная matrix Игрока 2 (Столбцы)

        Returns:
            Dict[str, Any]: Словарь с результатами аудита и вердиктом безопасности.
        """
        n, m = matrix_A.shape

        # 1. Поиск чистых стратегий Нэша (Эгоистичная рациональность)
        best_for_p1 = (matrix_A == jnp.max(matrix_A, axis=0, keepdims=True))
        best_for_p2 = (matrix_B == jnp.max(matrix_B, axis=1, keepdims=True))
        nash_mask = best_for_p1 & best_for_p2
        nash_indices = jnp.argwhere(nash_mask)

        # 2. Поиск Оптимума Парето (Глобальный альтруизм системы)
        total_welfare = matrix_A + matrix_B
        max_welfare = jnp.max(total_welfare)
        pareto_mask = (total_welfare == max_welfare)

        # 3. Проверка на пересечение (Рациональный Альтруизм)
        overlap_mask = nash_mask & pareto_mask
        has_perfect_balance = bool(jnp.any(overlap_mask))

        # 4. Вычисление дивергенции и выбор рабочей стратегии
        if has_perfect_balance:
            distance = 0.0
            best_cell = jnp.argwhere(overlap_mask)[0]  # Берем первый найденный оптимум
            row, col = best_cell, best_cell
        else:
            # Если точки разошлись, считаем евклидово расстояние между геометрическими масками
            nash_float = nash_mask.astype(float)
            pareto_float = pareto_mask.astype(float)
            distance = float(jnp.sqrt(jnp.sum((nash_float - pareto_float) ** 2)))

            # Если есть чистый Нэш - прагматично встаем в него, если нет - в нулевую позицию
            if len(nash_indices) > 0:
                row, col = nash_indices[0], nash_indices[0]
            else:
                row, col = 0, 0

        # Формируем результирующие векторы вероятностей для вывода
        x = jnp.zeros(n).at[row].set(1.0)
        y = jnp.zeros(m).at[col].set(1.0)

        is_safe = has_perfect_balance or (distance < self.threshold)

        return {
            "is_safe": is_safe,
            "divergence": distance,
            "strategy_p1": x,
            "strategy_p2": y,
            "has_perfect_balance": has_perfect_balance
        }


