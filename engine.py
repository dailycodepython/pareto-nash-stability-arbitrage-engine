    print("🚀 СИСТЕМА СДЕРЖИВАНИЯ: ЗАПУСК ПРИКЛАДНОГО ИНЖЕНЕРНОГО ПАЙПЛАЙНА")
    print("=" * 75 + "\n")

    # 1. Инициализируем наш ИИ-фильтр с порогом дивергенции 0.5
    engine = StabilityArbitrageEngine(threshold=0.5)

    # 2. Кодируем три прикладных сценария (матрицы А и B)

    # Сценарий А: Балансировка нагрузки микросервисов (Сонаправленные интересы)
    load_A = jnp.array([
        [0.0, 8.0, 4.0],
        [8.0, 0.0, 4.0],
        [4.0, 4.0, 2.0]
    ])
    load_B = load_A

    # Сценарий Б: Облачный арбитраж полосы пропускания (Жесткая нулевая сумма)
    band_A = jnp.array([
        [ 0.0, -2.0, -5.0],
        [ 2.0,  0.0, -3.0],
        [ 5.0,  3.0,  0.0]
    ])
    band_B = -band_A

    # Сценарий В: P2P-сеть обмена данными (Угроза эгоистичного фрирайдинга)
    p2p_A = jnp.array([
        [ 5.0,  2.0, -1.0],
        [ 6.0,  3.0,  0.0],
        [ 8.0,  4.0,  1.0]
    ])
    p2p_B = p2p_A.T

    # 3. Цикл автоматического аудита сред движком
    scenarios = [
        ("Балансировка нагрузки (Микросервисы)", load_A, load_B),
        ("Конкуренция за канал (Облачный арбитраж)", band_A, band_B),
        ("P2P Сеть обмена (Протокол данных)", p2p_A, p2p_B)
    ]

    for name, matrix_A, matrix_B in scenarios:
        report = engine.analyze_system(matrix_A, matrix_B)

        print(f"🖥️  Аудит архитектуры: {name}")
        print(f" -> Индекс дивергенции интересов: {report['divergence']:.4f}")
        print(f" -> Рабочий режим системы (Узел 1 / Узел 2): {report['strategy_p1']} / {report['strategy_p2']}")

        if report['is_safe']:
            print(" 🟢 ВЕРДИКТ: ПОДХОДИТ (Оптимум системы совпадает с выгодой узлов)")
        else:
            print(" 🔴 ВЕРДИКТ: ОТКЛОНИТЬ (Высокий риск деградации сети / Ловушка эгоизма)")
        print("-" * 75)

